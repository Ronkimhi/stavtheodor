DATE_HE = re.compile(r'<div class="post-date" data-l="he"[^>]*>.*?</div>', re.S)


def with_byline(inner, he=False, slug=None):
    """Who wrote the post, under its date and outside the post body (2026-11-18): the name links to /about/.
    he=True (a Hebrew address, slug given): the Hebrew line alone, BYLINE_HE_ADDRESS."""
    m = DATE_HE.search(inner)
    if not m:
        return inner
    line = (f'<p class="post-byline" lang="he" dir="rtl">{BYLINE_HE_ADDRESS[1].format(slug=slug)}</p>' if he
            else T(*BYLINE, tag="p", cls="post-byline"))
    return inner[:m.end()] + f'\n    {line}' + inner[m.end():]


DATE_EN = re.compile(r'\s*<div class="post-date" data-l="en"[^>]*>.*?</div>', re.S)


def hebrew_date(inner):
    """A Hebrew address shows the Hebrew date alone: the English twin goes, the Hebrew one keeps lang and dir."""
    inner = DATE_EN.sub('', inner, count=1)
    return re.sub(r'<div class="post-date" data-l="he"([^>]*)>', lambda m: f'<div class="post-date" lang="he"{m.group(1).replace(' lang="he"', '')}>', inner, count=1)


def page_titles():
    """Every site page's (title_en, title_he) by its address, for the link-only notes: content/pages/*.json, and
    /about/ from its built h1."""
    out = {}
    for f in glob.glob('content/pages/*.json'):
        d = json.load(open(f, encoding='utf-8'))
        out['/' + d['path'].strip('/') + '/'] = (d['title_en'], d.get('title_he') or d['title_en'])
    if os.path.exists('about/index.html'):
        h1 = re.search(r'<h1[^>]*>(.*?)</h1>', open('about/index.html', encoding='utf-8').read(), re.S)
        if h1:
            en = re.search(r'data-l="en"[^>]*>(.*?)</span>', h1.group(1), re.S)
            he = re.search(r'data-l="he"[^>]*>(.*?)</span>', h1.group(1), re.S)
            if en and he:
                out['/about/'] = (H.unescape(en.group(1)), H.unescape(he.group(1)))
    return out


