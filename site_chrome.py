def load_faq():
    faq = json.load(open(FAQ_FILE, encoding='utf-8'))
    for q in faq:
        for k in ('q_en', 'a_en', 'q_he', 'a_he'):
            assert q.get(k), f'faq.json: item missing {k}'
    return faq


def faq_schema(faq):
    return {
        '@context': 'https://schema.org',
        '@type': 'FAQPage',
        'mainEntity': [{'@type': 'Question', 'name': q['q_en'],
                        'acceptedAnswer': {'@type': 'Answer', 'text': q['a_en']}} for q in faq],
    }


def faq_details(faq, first_open=True):
    """The visible questions, the same text as the FAQPage schema, word for word."""
    return ''.join(f'''
      <details class="qa"{' open' if (i == 0 and first_open) else ''}>
        <summary><h3 class="serif">{T(H.escape(q["q_en"]), H.escape(q["q_he"]))}</h3><span class="plus" aria-hidden="true"></span></summary>
        <p class="body">{T(H.escape(q["a_en"]), H.escape(q["a_he"]))}</p>
      </details>''' for i, q in enumerate(faq))


def ld_script(block):
    text = block if isinstance(block, str) else json.dumps(block, ensure_ascii=False, indent=2)
    return f'<script type="application/ld+json">\n{text}\n</script>'


