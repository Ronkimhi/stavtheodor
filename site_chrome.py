# ---------------------------------------------------------------- guards
def guard_index():
    """index.html is generated by build-home.py. A post pasted into it by hand would be
    wiped by the next build, so every build refuses to run while one is there."""
    p = rel('index.html')
    if os.path.exists(p) and '<article class="post' in open(p, encoding='utf-8').read():
        raise SystemExit(
            'STOP: index.html contains an Art Radar <article class="post ...">.\n'
            'Posts live in content/posts.html (see ADD-BLOG-POST-GUIDE.md). index.html is generated.\n'
            'Move the post block (its JSON-LD <script> + <article>) to the top of content/posts.html,\n'
            'restore index.html (git checkout index.html), then run python3 build.py again. Nothing was written.'
        )


# ---------------------------------------------------------------- small helpers
def strip_tags(s):
    return H.unescape(re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', s or ''))).strip()


def first_sentence(s):
    s = strip_tags(s)
    m = re.match(r'(.+?[.!?])(\s|$)', s)
    return (m.group(1) if m else s).strip()


def T(en, he, tag='span', cls=''):
    """An English and a Hebrew twin. The site's switch shows one of them."""
    c = f' class="{cls}"' if cls else ''
    return f'<{tag}{c} data-l="en">{en}</{tag}><{tag}{c} data-l="he" dir="rtl">{he}</{tag}>'


