def read_posts(path=POSTS_FILE):
    """content/posts.html as text, and one dict per post, newest first (file order)."""
    src = open(path, encoding='utf-8', newline='').read()
    pairs = PAIR_RE.findall(src)
    if not pairs:
        raise SystemExit('No posts found in content/posts.html: check the JSON-LD <script> + <article class="post" id="slug"> structure.')
    posts = []
    for json_text, article_class, slug, inner in pairs:
        data = json.loads(json_text)

        def grab(rx):
            mm = re.search(rx, inner, flags=re.S)
            return strip_tags(mm.group(1)) if mm else ''
        date_en = grab(r'<div class="post-date" data-l="en">(.*?)</div>')
        date_he = grab(r'<div class="post-date" data-l="he"[^>]*>(.*?)</div>')
        title_en = title_he = ''
        for attrs, t in re.findall(r'<h2 class="post-title[^"]*"([^>]*)>(.*?)</h2>', inner, flags=re.S):
            tag = attrs + ' '
            if 'post-title-he' in tag or 'data-l="he"' in tag or 'dir="rtl"' in tag:
                title_he = title_he or strip_tags(t)
            else:
                title_en = title_en or strip_tags(t)
        m_en = re.search(r'<h2 class="post-title post-title-en"[^>]*>(.*?)</h2>', inner, flags=re.S)
        m_he = re.search(r'<h2 class="post-title post-title-he"[^>]*>(.*?)</h2>', inner, flags=re.S)
        if m_en:
            title_en = strip_tags(m_en.group(1))
        if m_he:
            title_he = strip_tags(m_he.group(1))
        en_body = re.search(r'<div class="post-body post-body-en"[^>]*>(.*?)$', inner, flags=re.S)
        he_body = re.search(r'<div class="post-body" lang="he"[^>]*>(.*?)<div class="post-body post-body-en"', inner, flags=re.S)
        p_en = re.search(r'<p[^>]*>(.*?)</p>', en_body.group(1), flags=re.S) if en_body else None
        p_he = re.search(r'<p[^>]*>(.*?)</p>', he_body.group(1), flags=re.S) if he_body else None
        img = re.search(r'<img[^>]+src="([^"]+)"', inner)
        img_src = img.group(1) if img else ''
        if img_src and not img_src.startswith('/'):
            img_src = '/' + img_src
        assert date_en and date_he and title_en and title_he, f'post {slug}: date or title twin missing'
        posts.append(dict(
            slug=slug, article_class=article_class, json_text=json_text, article_inner=inner,
            headline=data['headline'], description=data['description'],
            datePublished=data['datePublished'], dateModified=data.get('dateModified', data['datePublished']),
            date_en=date_en, date_he=date_he, title_en=title_en, title_he=title_he,
            teaser_en=first_sentence(p_en.group(1)) if p_en else '',
            teaser_he=first_sentence(p_he.group(1)) if p_he else '',
            img=img_src,
            og_image=(SITE + img_src) if img_src else (SITE + '/og-image.jpg'),
        ))
    return src, posts


def month_labels(post):
    m = re.match(r'([A-Za-z]+) \d+, (\d{4})', post['date_en'])
    en = f'{m.group(1)} {m.group(2)}' if m else post['date_en']
    mh = re.match(r'\d+ ב(.+)$', post['date_he'])
    he = mh.group(1) if mh else post['date_he']
    return en, he


def timeline(posts, with_months):
    """The posts as timeline entries (the homepage, /radar/, and the More list on a post)."""
    out = []
    last = None
    for p in posts:
        mon = month_labels(p)
        if with_months and mon != last:
            out.append(f'<div class="month"><p class="eyebrow">{T(mon[0], mon[1])}</p></div>')
            last = mon
        th = f'<div class="th"><img src="{p["img"]}" alt="" loading="lazy"></div>' if p['img'] else '<div class="th"></div>'
        teaser = f'<p class="teaser">{T(H.escape(p["teaser_en"]), H.escape(p["teaser_he"]))}</p>' if p['teaser_en'] else ''
        out.append(f'''
      <a class="entry reveal" href="/radar/{p['slug']}/">
        <div class="date">{T(p['date_en'], p['date_he'])}</div>
        <div><h3 class="serif">{T(H.escape(p['title_en']), H.escape(p['title_he']))}</h3>{teaser}</div>
        {th}
      </a>''')
    return ''.join(out)


