def faq_schema(faq):
    return {
        '@context': 'https://schema.org',
        '@type': 'FAQPage',
        'mainEntity': [{'@type': 'Question', 'name': q['q_en'],
                        'acceptedAnswer': {'@type': 'Answer', 'text': q['a_en']}} for q in faq],
    }


