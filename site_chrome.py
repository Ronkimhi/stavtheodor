def strip_tags(s):
    return H.unescape(re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', s or ''))).strip()


def first_sentence(s):
    s = strip_tags(s)
    m = re.match(r'(.+?[.!?])(\s|$)', s)
    return (m.group(1) if m else s).strip()


